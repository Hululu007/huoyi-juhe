/// 内置导入站种子：随包发布的 py / 阅读 JSON 站。
///
/// 模型走现有导入模型（pyImport / legadoImport），不造新客户端类型：
/// 文件随包发在 assets/builtin_sites/，首启从 asset 拷到导入目录后
/// 按正常导入条目登记（builtin=true，id 稳定为 `seed_<seedId>`）。
/// 用户在站源管理删掉后记墓碑，不再复活（见 SourceRegistry 的
/// _deletedSeeds）。柚子短剧 2026-11-24 随魔蚁 v63 合入：魔蚁版补了
/// /api/playback 取流与 IncompleteRead 续读，取流不稳定项已修，
/// 名字带「短剧」自动归短剧区。
class BuiltinImportedSeed {
  const BuiltinImportedSeed({
    required this.seedId,
    required this.asset,
    required this.fileName,
    required this.name,
    required this.kind,
    this.contentTypeKey,
    this.verifyNote,
  });

  final String seedId;
  final String asset;
  final String fileName;
  final String name;
  final SourceKind kind;

  /// 显式内容分型（ContentType.key）：种子登记时写进条目 extra，
  /// 替代默认的 'video'。音乐/听书类 py 靠机器检测分不开
  /// （同是音频标记），必须靠种子显式选型区分；为空时按旧口径
  /// 登记为 'video'。
  final String? contentTypeKey;

  /// 验证状态标记：null = 已实测全链验通；非空 = 未全链验通的
  /// 原因短句（如「搜索依赖 JS 规则，本机未实测」）。登记时写进
  /// 条目 extra['verifyNote']，并拼进 detail 显示成
  /// 「内置导入站 · 未验通：<原因>」，用户在站源管理里能分辨。
  /// 口径（用户书源定版）：能被引擎正常加载的源都登记进来，
  /// 验不通的靠这条标记区分，不冒充验通。
  final String? verifyNote;
}

